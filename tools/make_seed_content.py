def main() -> int:
    content_dir = CONTENT_DIR
    packs_dir = os.path.join(content_dir, "packs")
    os.makedirs(packs_dir, exist_ok=True)

    used_ids: set[str] = set()
    for pack in PACKS:
        pack_id = pack["id"]
        if pack_id in used_ids:
            print(f"Duplicate pack id: {pack_id}")
            return 1
        used_ids.add(pack_id)

        assets = []
        image_ids = []
        for entry_data in pack["entries"]:
            for image_id in entry_data.get("imageIds", []):
                if image_id not in image_ids:
                    image_ids.append(image_id)
        # A question may show a picture that no topic uses.
        for question_data in pack["questions"]:
            image_id = question_data.get("imageId")
            if image_id and image_id not in image_ids:
                image_ids.append(image_id)
        for index, image_id in enumerate(image_ids):
            assets.append(
                {
                    "id": image_id,
                    "full": f"images/{image_id}.webp",
                    "thumb": f"images/{image_id}.thumb.webp",
                }
            )

        questions = []
        for question in pack["questions"]:
            item = dict(question)
            if item.get("imageId") is None:
                item.pop("imageId", None)
            questions.append(item)

        published = {
            "packId": pack_id,
            "packVersion": "1.0.0",
            "schemaVersion": 1,
            "title": pack["title"],
            "description": pack["description"],
            "icon": pack["icon"],
            "ageRange": "6-8",
            "color": pack["color"],
            "entries": pack["entries"],
            "questions": questions,
            "assets": assets,
            "attributions": {},
        }

        path = os.path.join(packs_dir, pack_id, f"{pack_id}.src.json")
        write_json(path, published)
        print(
            f"wrote {pack_id}: {len(published['entries'])} topics, "
            f"{len(published['questions'])} questions, {len(assets)} images"
        )

    write_json(
        os.path.join(content_dir, "library.json"),
        {
            "libraryVersion": "2026.11.14-1",
            "libraryVersionNumber": 1,
            "minAppVersion": "1.0.0",
            "title": "Kids Discovery World Content Library",
        },
    )
    print(f"\n{len(PACKS)} packs written to {packs_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
