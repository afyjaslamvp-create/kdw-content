def mc(qid, prompt, options, answer, explanation, image=None, tags=()):
    """Multiple choice question."""
    return {
        "id": qid,
        "type": "multiple-choice",
        "prompt": prompt,
        "options": list(options),
        "answerIndex": answer,
        "explanation": explanation,
        "imageId": image,
        "difficulty": 1,
        "tags": list(tags),
    }


def tf(qid, prompt, answer, explanation, image=None, tags=()):
    """True or false question."""
    return {
        "id": qid,
        "type": "true-false",
        "prompt": prompt,
        "answer": answer,
        "explanation": explanation,
        "imageId": image,
        "difficulty": 1,
        "tags": list(tags),
    }


def sa(qid, prompt, answers, explanation, image=None, tags=()):
    """Short answer question."""
    return {
        "id": qid,
        "type": "short-answer",
        "prompt": prompt,
        "acceptedAnswers": list(answers),
        "explanation": explanation,
        "imageId": image,
        "difficulty": 2,
        "tags": list(tags),
    }


def entry(eid, title, summary, body, facts, image=None, keywords=()):
    return {
        "id": eid,
        "title": title,
        "summary": summary,
        "body": body,
        "facts": list(facts),
        "imageIds": [image] if image else [],
        "keywords": list(keywords),
        "readMinutes": 2,
    }


